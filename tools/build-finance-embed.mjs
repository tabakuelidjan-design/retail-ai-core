// Builds src/finance/ui/finance-embed.js: the Finance UI as ONE script that the Nordla Core page loads (no iframe, no eval).
// The Finance scripts keep their own code unchanged; they are wrapped in a function whose parameters (document, location, history,
// window) are the isolated ones from embed/shim.js. Run: node tools/build-finance-embed.mjs  (or --check to verify it is up to date).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const UI = path.join(ROOT, 'src/finance/ui');
const SHARED = path.join(ROOT, 'src/shared');
const OUT_DIR = path.join(ROOT, 'src/finance-embed');
const OUT = path.join(OUT_DIR, 'finance-embed.js');

// Same order as index.html (the rail script is the standalone Finance navigation: Core provides it on the embedded page).
const SCRIPTS = [
  { file: path.join(SHARED, 'nordla-icon.js') },
  { file: path.join(SHARED, 'nordla-charts.js') },
  { file: path.join(UI, 'lang-fr.js') }, { file: path.join(UI, 'lang-nl.js') }, { file: path.join(UI, 'i18n.js') },
  { file: path.join(UI, 'bank-connect.js') }, { file: path.join(UI, 'civil-date.js') }, { file: path.join(UI, 'bank-csv.js') },
  { file: path.join(UI, 'app.js') }, { file: path.join(UI, 'views-workspace.js') }, { file: path.join(UI, 'views-contacts.js') },
  { file: path.join(UI, 'views-pack.js') },
  { file: path.join(UI, 'pdf-preview.js') },
];
const STYLES = [path.join(SHARED, 'nordla-fonts.css'), path.join(UI, 'nordla-tokens.css'), path.join(SHARED, 'nordla-charts.css'), path.join(UI, 'style.css')];

/** The Finance styles, made to live inside the Shadow DOM: the document-level selectors become the host's. */
export function embedCss() {
  return STYLES.map((f) => readFileSync(f, 'utf8'))
    .join('\n')
    .replace(/:root\b/g, ':host')
    .replace(/\bhtml,\s*body\b/g, ':host');
}

export function buildEmbed() {
  const shim = readFileSync(path.join(UI, 'embed/shim.js'), 'utf8');
  // Every window.NAME the scripts assign is bound to a local const right after its file: the bundle runs in its own scope.
  const bound = new Set();
  const body = SCRIPTS.map(({ file }) => {
    const text = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
    const names = [...new Set([...text.matchAll(/window\.([A-Za-z_][A-Za-z0-9_]*) = /g)].map((m) => m[1]))].filter((n) => !bound.has(n));
    names.forEach((n) => bound.add(n));
    const after = names.map((n) => `const ${n} = window.${n};`).join(' ');
    return `  // ---- ${path.relative(ROOT, file).replace(/\\/g, '/')} ----\n${text}\n${after ? `  ${after}\n` : ''}`;
  }).join('\n');
  return `// GENERATED by tools/build-finance-embed.mjs from the Finance UI sources. Do not edit by hand.
// Loaded by the Nordla Core page: window.__nordlaFinanceEmbed(shadowRoot, { apiBase }). No eval, no inline script.
(function () {
${shim.replace(/\r\n/g, '\n').split('\n').map((l) => (l ? `  ${l}` : l)).join('\n')}
  var FIN_CSS = ${JSON.stringify(embedCss())};
  window.__nordlaFinanceEmbed = function (shadowRoot, options) {
    const env = createFinanceEnv(shadowRoot, { apiBase: (options && options.apiBase) || '', css: FIN_CSS });
    const document = env.document, location = env.location, history = env.history, window = env.window, finApiBase = env.apiBase;
${body}
    return true;
  };
})();
`;
}

const built = buildEmbed();
if (process.argv.includes('--check')) {
  const current = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return null; } })();
  if (current !== built) { console.error('finance-embed.js is out of date: run node tools/build-finance-embed.mjs'); process.exit(1); }
  console.log('finance-embed.js is up to date');
} else {
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT, built);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${built.length} bytes)`);
}
