// Nordla HTTP security (Core C4) - trusted request context, host and origin checks.
//
// Two explicit proxy modes, chosen by configuration (never guessed from the request):
//   'none'     (local)   client IP = the TCP socket address; every proxy header (X-Real-IP, X-Forwarded-*) is IGNORED;
//                        host = the Host header, protocol = http unless the socket is TLS.
//   'railway'  (hosted)  Railway's edge proxy overwrites X-Real-IP with the connecting client IP, sets X-Forwarded-Proto (https)
//                        and X-Forwarded-Host (the public domain). Each must be present exactly once and well formed; the protocol
//                        must be https. X-Forwarded-For is NEVER used (a client can prepend values to it).
// A fresh request id is always generated by Nordla (an incoming X-Request-Id is ignored). The client IP is only handed to the
// attempt limiter; it is never logged (see redact.js).
//
// The merchant is NEVER derived from the host or the origin: it always comes from the session (C3).

import { randomUUID } from 'node:crypto';
import { isIP } from 'node:net';
import { HttpSecurityError } from './redact.js';

export const SAFE_METHODS = Object.freeze(['GET', 'HEAD', 'OPTIONS']);

/** Lower-cased host[:port] with the default port removed; null when not a plain host. */
export function normalizeHost(raw, scheme = 'https') {
  if (typeof raw !== 'string') return null;
  const s = raw.trim().toLowerCase();
  if (!s || s.length > 255 || /[\s,/\\@?#*]/.test(s)) return null;
  let url;
  try { url = new URL(`${scheme}://${s}`); } catch { return null; }
  if (url.username || url.password || url.pathname !== '/' || url.search || url.hash) return null;
  return url.port ? `${url.hostname}:${url.port}` : url.hostname;
}

/** Exact origin "scheme://host[:port]" (lower case, default port removed); null for anything else (paths, "null", wildcards...). */
export function normalizeOrigin(raw) {
  if (typeof raw !== 'string') return null;
  const s = raw.trim().toLowerCase();
  if (!s || s.includes('*') || /[\s,]/.test(s)) return null;
  let url;
  try { url = new URL(s); } catch { return null; }
  if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password) return null;
  return s === url.origin ? url.origin : null; // exactly scheme://host[:port] - no path, no trailing slash, no default port
}

/** One header value: undefined when absent; throws on a repeated header (Node joins repeats with ", " or gives an array). */
function single(req, name) {
  const v = req.headers?.[name];
  if (v === undefined) return undefined;
  if (Array.isArray(v) || String(v).includes(',')) throw new HttpSecurityError('BAD_REQUEST', `PROXY_HEADER_AMBIGUOUS_${name.toUpperCase().replace(/-/g, '_')}`);
  return String(v).trim();
}

/**
 * @param {import('node:http').IncomingMessage} req
 * @param {{ proxy: 'none'|'railway', hosted: boolean, allowedHosts: readonly string[] }} cfg
 * @returns {Readonly<{ requestId: string, method: string, host: string, protocol: 'http'|'https', clientIp: string|null, origin: string|null, secFetchSite: string|null }>}
 * @throws {HttpSecurityError} FORBIDDEN (unknown host) / BAD_REQUEST (malformed or ambiguous proxy data)
 */
export function requestContext(req, cfg, { newId = randomUUID } = {}) {
  const requestId = newId();
  const method = String(req.method ?? '').toUpperCase();
  let host; let protocol; let clientIp;
  if (cfg.proxy === 'railway') {
    const realIp = single(req, 'x-real-ip');
    const proto = single(req, 'x-forwarded-proto');
    const fwdHost = single(req, 'x-forwarded-host');
    if (!realIp || isIP(realIp) === 0) throw new HttpSecurityError('BAD_REQUEST', 'PROXY_CLIENT_IP_INVALID');
    if (proto !== 'https') throw new HttpSecurityError('BAD_REQUEST', 'PROXY_PROTOCOL_NOT_HTTPS');
    host = normalizeHost(fwdHost ?? '', 'https');
    if (!host) throw new HttpSecurityError('BAD_REQUEST', 'PROXY_HOST_INVALID');
    protocol = 'https'; clientIp = realIp;
  } else {
    protocol = req.socket?.encrypted ? 'https' : 'http';
    host = normalizeHost(single(req, 'host') ?? '', protocol);
    clientIp = typeof req.socket?.remoteAddress === 'string' && isIP(req.socket.remoteAddress) ? req.socket.remoteAddress : null;
    if (!host) throw new HttpSecurityError('BAD_REQUEST', 'HOST_INVALID');
  }
  if (cfg.hosted && protocol !== 'https') throw new HttpSecurityError('FORBIDDEN', 'HTTPS_REQUIRED');
  if (!cfg.allowedHosts.includes(host)) throw new HttpSecurityError('FORBIDDEN', 'HOST_NOT_ALLOWED');
  const rawOrigin = single(req, 'origin');
  const sfs = single(req, 'sec-fetch-site');
  return Object.freeze({
    requestId, method, host, protocol, clientIp,
    origin: rawOrigin === undefined ? null : (normalizeOrigin(rawOrigin) ?? 'invalid'),
    secFetchSite: sfs === undefined ? null : sfs.toLowerCase(),
  });
}

/**
 * Same-origin rule. Safe methods (GET / HEAD / OPTIONS) pass without an Origin (a future route may still demand one). Any other
 * method needs an Origin header that is EXACTLY one of the configured origins AND whose host is the request's host; a
 * Sec-Fetch-Site other than same-origin is refused. No CORS: nothing here ever allows a foreign origin.
 * @returns {{ ok: true } | { ok: false, code: string }}
 */
export function checkOrigin(ctx, cfg, { requireOrigin = !SAFE_METHODS.includes(ctx.method) } = {}) {
  if (ctx.origin === null) return requireOrigin ? { ok: false, code: 'ORIGIN_MISSING' } : { ok: true };
  if (ctx.origin === 'invalid' || !cfg.allowedOrigins.includes(ctx.origin)) return { ok: false, code: 'ORIGIN_NOT_ALLOWED' };
  if (new URL(ctx.origin).host !== ctx.host || `${new URL(ctx.origin).protocol.slice(0, -1)}` !== ctx.protocol) return { ok: false, code: 'ORIGIN_NOT_SAME_HOST' };
  if (ctx.secFetchSite !== null && ctx.secFetchSite !== 'same-origin') return { ok: false, code: 'FETCH_SITE_NOT_SAME_ORIGIN' };
  return { ok: true };
}
