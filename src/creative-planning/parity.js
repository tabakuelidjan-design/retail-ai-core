import { createHash } from 'node:crypto';

import { auditSpecStage } from '../creative-brain/parity.js';
import {
  buildCopyAdaptInstruction, buildCopyWriteInstruction, COPY_ADAPT_RULES, COPY_ADAPT_SPEC, COPY_WRITE_RULES, COPY_WRITE_SPEC,
} from './copy-policy.js';

// THE PARITY AUDIT OF THE PLANNING STAGES. The same mechanical check as the Creative Brain's (every validator rule is stated in the instruction, every instruction rule is enforced), applied to the two
// stages that may ask a language model: COPY_ADAPT and COPY_WRITE. The other planning stages are deterministic and receive no model answer: they appear in the matrix as such.

const SAMPLE_FACT = Object.freeze({ fact_ref: 'fact://sample', kind: 'DESCRIPTIVE', status: 'VERIFIED', statement: 'A sample verified fact.' });

export const PLANNING_STAGE_CONTRACTS = Object.freeze([
  {
    stage: 'COPY_ADAPT', model: true, spec: COPY_ADAPT_SPEC, rules: COPY_ADAPT_RULES, instruction: () => buildCopyAdaptInstruction({ source: 'A sample text.', role: 'HEADLINE', capacityChars: 100, locale: 'en' }), validator: 'src/creative-planning/copy-policy.js#verifyAdaptation',
  },
  {
    stage: 'COPY_WRITE', model: true, spec: COPY_WRITE_SPEC, rules: COPY_WRITE_RULES, instruction: () => buildCopyWriteInstruction({ purpose: 'HEADLINE', facts: [SAMPLE_FACT], objective: 'UNKNOWN', audience: 'UNKNOWN', capacityChars: 100, locale: 'en' }), validator: 'src/creative-planning/copy-policy.js#verifyGeneration',
  },
]);

export const PLANNING_DETERMINISTIC_STAGES = Object.freeze([
  { stage: 'INPUT_UNDERSTANDING', model: false, derivation: 'understandInputs(sources, ports): one normalized observation per input; a port only enriches it and a failing port leaves it NOT_ANALYZED', validator: 'src/creative-planning/understanding.js#normalizeObservation' },
  { stage: 'CONTENT_ANALYSIS', model: false, derivation: 'buildInventory(request, observations): measured sizes, copy modes and fact statuses; no decision', validator: 'src/creative-planning/inventory.js#buildInventory' },
  { stage: 'FORMAT_PLAN', model: false, derivation: 'the format planner: a format chosen by named rules from the inventory, the channel and the constraints; text distributed verbatim over assets and caption', validator: 'src/creative-planning/format-planner.js#createContentFormatPlanner' },
]);

/** The matrix and the verdict of the planning stages (empty `failures` when instruction and validator agree everywhere). */
export function auditPlanningParity() {
  const stages = []; const failures = []; const rows = [];
  for (const c of PLANNING_STAGE_CONTRACTS) { const a = auditSpecStage(c); stages.push({ stage: c.stage, model: true, instruction_sha256: a.instruction_sha256, rows: a.rows.length, failures: a.failures.length }); rows.push(...a.rows); failures.push(...a.failures); }
  for (const d of PLANNING_DETERMINISTIC_STAGES) { stages.push({ stage: d.stage, model: false, derivation: d.derivation }); rows.push({ stage: d.stage, kind: 'DETERMINISTIC', path: d.stage, rule: d.derivation, instruction: null, validator: d.validator, stated: null }); }
  return { ready: failures.length === 0, stages, rows, failures };
}

/** The matrix as markdown. Long hashes are shortened: a committed document never carries a 64-character hex string (the repository's privacy test). */
export function renderPlanningContractMatrix(audit = auditPlanningParity()) {
  const lines = ['# Creative planning contract matrix', '', 'Generated by `auditPlanningParity()` from the real instructions and validators. Do not edit by hand.', ''];
  for (const s of audit.stages) {
    lines.push(`## ${s.stage}`, '');
    if (!s.model) { lines.push(`No model answer: ${s.derivation}`, ''); continue; }
    lines.push(`Instruction sha256 \`${s.instruction_sha256}\`. ${s.rows} rows, ${s.failures} parity failures.`, '', '| kind | path / rule id | instruction text | validator | enforced |', '|---|---|---|---|---|');
    for (const r of audit.rows.filter((x) => x.stage === s.stage)) lines.push(`| ${r.kind} | ${String(r.path).replace(/\|/g, '/')} | ${String(r.instruction ?? '').replace(/\|/g, '/').slice(0, 230)} | ${r.validator} | ${r.enforced ?? 'SPEC'} |`);
    lines.push('');
  }
  lines.push(audit.ready ? 'PARITY: every validator rule is stated in the instruction and every instruction rule is enforced or declared advisory.' : `PARITY FAILURES:\n${audit.failures.map((f) => `- ${f}`).join('\n')}`);
  return `${lines.join('\n').replace(/\b([0-9a-f]{16})[0-9a-f]{48}\b/g, '$1')}\n`;
}

export const planningInstructionHash = (stage) => createHash('sha256').update(PLANNING_STAGE_CONTRACTS.find((c) => c.stage === stage).instruction().system).digest('hex').slice(0, 16);
