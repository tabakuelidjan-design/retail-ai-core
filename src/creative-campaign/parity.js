import { auditSpecStage } from '../creative-brain/parity.js';
import { SAMPLE_CONCEPT } from '../creative-brain/parity.js';
import { buildAssetBriefInstruction, ASSET_BRIEF_RULES, ASSET_BRIEF_SPEC } from './asset-director.js';

// THE PARITY AUDIT OF THE CAMPAIGN STAGES. The one stage of the campaign that asks a model, the imagery brief of an asset, is audited like every model stage of the Creative Brain: every validator rule is
// stated in the instruction and every instruction rule is enforced or declared advisory. The other stages are deterministic and receive no model answer: they appear in the matrix as such.

const SAMPLE_ART = Object.freeze({
  atmosphere: 'A quiet morning workshop', material_language: 'worn wood and matte paper', lighting_intent: 'soft side light', depth_model: 'SHALLOW_LAYERS', visual_rhythm: 'MEASURED', realism: 'PHOTOREALISTIC', emotional_temperature: 'WARM',
});
const SAMPLE_ASSET = Object.freeze({
  position: 2, of: 5, narrative_role: 'PROGRESSION', density_class: 'MEDIUM', composition_intent: 'SPLIT_PANEL', imagery_intent: 'PRODUCT_DETAIL', crop_scale: 'MID', copy: [{ role: 'BODY', text: 'A sample sentence.' }], hint: null,
});

export const CAMPAIGN_STAGE_CONTRACTS = Object.freeze([
  {
    stage: 'ASSET_BRIEF', model: true, spec: ASSET_BRIEF_SPEC, rules: ASSET_BRIEF_RULES, instruction: () => buildAssetBriefInstruction({ concept: SAMPLE_CONCEPT, artDirection: SAMPLE_ART, asset: SAMPLE_ASSET }), validator: 'src/creative-campaign/asset-director.js#createAssetDirector',
  },
]);

export const CAMPAIGN_DETERMINISTIC_STAGES = Object.freeze([
  { stage: 'SEQUENCE', model: false, derivation: 'planSequence(assets, densities, objective): a narrative role per asset from the content, then a composition and an imagery intent that suit the role and the density and never repeat the previous look', validator: 'src/creative-campaign/sequence.js#planSequence' },
  { stage: 'CONTINUITY', model: false, derivation: 'buildContinuityContract(frame, concept, art direction, brief): what stays consistent across the assets and what varies', validator: 'src/creative-campaign/continuity.js#buildContinuityContract' },
  { stage: 'DIVERSITY', model: false, derivation: 'auditDiversity(asset plans): measured rules against a repeated template', validator: 'src/creative-campaign/continuity.js#auditDiversity' },
  { stage: 'CAMPAIGN_BUDGET', model: false, derivation: 'chooseProductionEnvelope and createCampaignBudget: a worst-case estimate reserved against the ceiling before any cost', validator: 'src/creative-campaign/budget.js#createCampaignBudget' },
  { stage: 'CAMPAIGN_STATE', model: false, derivation: 'the working state: nodes stored with the hash of their inputs, reused only when the hash is unchanged', validator: 'src/creative-campaign/state.js#reusable' },
]);

export function auditCampaignParity() {
  const stages = []; const failures = []; const rows = [];
  for (const c of CAMPAIGN_STAGE_CONTRACTS) { const a = auditSpecStage(c); stages.push({ stage: c.stage, model: true, instruction_sha256: a.instruction_sha256, rows: a.rows.length, failures: a.failures.length }); rows.push(...a.rows); failures.push(...a.failures); }
  for (const d of CAMPAIGN_DETERMINISTIC_STAGES) { stages.push({ stage: d.stage, model: false, derivation: d.derivation }); rows.push({ stage: d.stage, kind: 'DETERMINISTIC', path: d.stage, rule: d.derivation, instruction: null, validator: d.validator, stated: null }); }
  return { ready: failures.length === 0, stages, rows, failures };
}

export function renderCampaignContractMatrix(audit = auditCampaignParity()) {
  const lines = ['# Creative campaign contract matrix', '', 'Generated by `auditCampaignParity()` from the real instructions and validators. Do not edit by hand.', ''];
  for (const s of audit.stages) {
    lines.push(`## ${s.stage}`, '');
    if (!s.model) { lines.push(`No model answer: ${s.derivation}`, ''); continue; }
    lines.push(`Instruction sha256 \`${s.instruction_sha256}\`. ${s.rows} rows, ${s.failures} parity failures.`, '', '| kind | path / rule id | instruction text | validator | enforced |', '|---|---|---|---|---|');
    for (const r of audit.rows.filter((x) => x.stage === s.stage)) lines.push(`| ${r.kind} | ${String(r.path).replace(/\|/g, '/')} | ${String(r.instruction ?? '').replace(/\|/g, '/').slice(0, 230)} | ${r.validator} | ${r.enforced ?? 'SPEC'} |`);
    lines.push('');
  }
  lines.push(audit.ready ? 'PARITY: every validator rule is stated in the instruction and every instruction rule is enforced or declared advisory.' : `PARITY FAILURES:\n${audit.failures.map((f) => `- ${f}`).join('\n')}`);
  return `${lines.join('\n').replace(/\b([0-9a-f]{16})[0-9a-f]{48}\b/g, '$1')}\n`;
}
