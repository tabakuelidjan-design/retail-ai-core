-- Finance CORE - ESSENTIAL BANK. Builds on 20261003090000 (P0 integrity) and 20261004090000 (essential payments); none of the three is applied to production yet: apply them in order.
-- ADDITIVE: nothing dropped, no row rewritten except two backfills of NEW columns (account links). Legacy columns of fin_bank_transactions (status, matched_*) stay but stop being authoritative.
--
-- THE MODEL
--   Bank account        fin_bank_accounts          identity of an account (provider id or the CSV pseudo-account), currency, MASKED iban, status. Never a credential.
--   Bank transaction    fin_bank_transactions      an OBSERVED bank movement. Immutable facts. NOT a Finance payment.
--   Reconciliation      fin_bank_reconciliations   append-only link  bank transaction <-> payment (kind MATCH) or "deliberately set aside" (kind IGNORE); N<->M, partial, reversible.
--   Payment truth       fin_payment_registry + allocations (unchanged, still the only authority on payments, allocations, refunds, reversals and document status).
--   Derived             reconciled / ignored / remaining of a transaction, and its reconciliation status, come ONLY from the reconciliation rows (fin_bank_tx_amounts).
--                       fin_bank_transactions.status and matched_amount_cents/matched_at are a MIRROR written by a trigger; matched_kind/matched_document_id/matched_payment_id are dead legacy.
--
-- AMOUNTS of a transaction T (integer cents, one currency):  abs = |amount|;  matched = net MATCH rows;  ignored = net IGNORE rows;  remaining = abs - matched - ignored
--   Invariants (PostgreSQL): remaining >= 0 ; a MATCH never exceeds the payment (amount - its reversals) ; direction (IN tx <-> IN payment, OUT <-> OUT) and currency agree ;
--   an unreconcile never exceeds what the reconciliation row still holds ; a payment that is reconciled cannot be voided (unreconcile first).
-- LOCKING ORDER (extends the payments order): document -> payment -> bank transaction. A reconciliation locks its payment, then its transaction.
-- ATOMICITY: fin_bank_reconcile_and_pay creates the payment AND the reconciliation in ONE transaction: a failed payment can never leave a claimed transaction behind.

-- ---------- accounts ----------
create table fin_bank_accounts (
  id uuid primary key default gen_random_uuid(),
  merchant_id uuid not null references merchants(id),
  external_id text not null check (length(external_id) between 1 and 200),
  origin text not null check (origin in ('PROVIDER', 'CSV')),
  provider text,
  display_name text check (length(display_name) <= 120),
  iban_masked text check (iban_masked is null or (position('*' in iban_masked) > 0 and length(iban_masked) <= 40)), -- a full IBAN is never stored here
  currency text not null check (currency ~ '^[A-Z]{3}$'),
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'CLOSED')),
  created_at timestamptz not null default now(),
  closed_at timestamptz,
  constraint fin_bank_accounts_external_uq unique (merchant_id, external_id),
  constraint fin_bank_accounts_id_merchant_uq unique (id, merchant_id)
);
alter table fin_bank_accounts enable row level security;
revoke all on fin_bank_accounts from anon, authenticated;

