-- every transaction/balance is attached to an account of the SAME merchant and the SAME currency (the account is created on first sight: old callers keep working)
create function fin_bank_account_link() returns trigger language plpgsql as $$
declare acc fin_bank_accounts%rowtype;
begin
  if new.bank_account_id is null then
    insert into fin_bank_accounts (merchant_id, external_id, origin, currency)
      values (new.merchant_id, new.account_id, case when new.account_id = 'csv-import' then 'CSV' else 'PROVIDER' end, new.currency) on conflict (merchant_id, external_id) do nothing;
    select * into acc from fin_bank_accounts where merchant_id = new.merchant_id and external_id = new.account_id;
    new.bank_account_id := acc.id;
  else
    select * into acc from fin_bank_accounts where id = new.bank_account_id and merchant_id = new.merchant_id;
    if not found then raise exception 'FIN_BANK_ACCOUNT_NOT_FOUND'; end if;
    if acc.external_id <> new.account_id then raise exception 'FIN_BANK_ACCOUNT_MISMATCH: % vs %', acc.external_id, new.account_id; end if;
  end if;
  if acc.currency <> new.currency then raise exception 'FIN_BANK_CURRENCY_MISMATCH: account %, row %', acc.currency, new.currency; end if;
  return new;
end $$;
create trigger fin_bank_tx_account_link_trg before insert on fin_bank_transactions for each row execute function fin_bank_account_link();
create trigger fin_bank_balances_account_link_trg before insert or update on fin_bank_balances for each row execute function fin_bank_account_link();

